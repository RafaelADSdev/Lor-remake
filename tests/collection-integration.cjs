const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ offline: true, reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(), errors = [], remote = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/^https?:/.test(request.url())) remote.push(request.url()); });
    await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
    assert.equal(await page.locator('#open-full-catalog').count(), 0);
    assert.equal(await page.evaluate(() => typeof FullCatalogMode), 'undefined');
    assert.ok(await page.locator('#deck optgroup[label="Novos decks"] option').count() >= 12);
    await page.click('#build-deck');
    assert.equal(await page.locator('#catalog-source').inputValue(), 'official');
    assert.match(await page.locator('#collection-count').innerText(), /1647/);
    await page.click('#new-deck');
    await page.selectOption('#catalog-source', 'new');
    await page.fill('#card-search', 'Braum');
    await page.getByRole('button', { name: 'Ver detalhes de Braum', exact: true }).click();
    assert.equal(await page.getByText('Jogar esta carta no modo livre', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Adicionar Braum', exact: true }).isEnabled(), true);
    await page.selectOption('#collection-preset', 'braum_poros');
    await page.click('#load-featured-deck');
    assert.match(await page.locator('#deck-counter').innerText(), /40\/40/);
    await page.fill('#deck-name', 'Braum da minha coleção');
    await page.screenshot({ path: path.resolve(__dirname, '../test-results/collection-v30-desktop.png') });
    await page.click('#save-deck');
    await page.click('#start');
    await page.waitForFunction(() => state?.players[0].deckName === 'Braum da minha coleção');
    assert.equal(await page.evaluate(() => ['deck', 'board', 'hand'].flatMap(zone => state.players[0][zone]).filter(card => card.code === '01FR009').length), 3);
    await page.click('#menu');
    await page.click('#build-deck');
    await page.selectOption('#catalog-source', 'official');
    await page.fill('#card-search', '01FR009');
    for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Remover Braum', exact: true }).click();
    await page.fill('#card-search', '06RU026');
    for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Adicionar Aatrox', exact: true }).click();
    await page.click('#save-deck');
    assert.equal(await page.locator('#deck').inputValue(), 'demacia', 'editing an active deck into a pending deck must retire its stale playable version');
    assert.equal(await page.locator('#deck option[value="custom"]').count(), 0);
    await page.click('#new-deck');
    await page.fill('#deck-name', 'Aatrox na minha coleção');
    for (const code of ['06RU026','01DE039','01DE049','01DE020','01DE046','01DE028','01DE030','01DE056','01DE018','01DE012','01DE021','01DE007','01DE037','01DE032']) {
      await page.fill('#card-search', code);
      const name = await page.evaluate(code => OFFICIAL_CATALOG[code].name, code);
      const add = page.getByRole('button', { name: 'Adicionar ' + name, exact: true });
      for (let i = 0; i < (code === '01DE032' ? 1 : 3); i++) await add.click();
    }
    assert.match(await page.locator('#deck-counter').innerText(), /40\/40/);
    assert.match(await page.locator('#deck-error').innerText(), /ainda sem regras/);
    assert.equal(await page.locator('#save-deck').isEnabled(), true);
    assert.equal(await page.locator('#save-deck').innerText(), 'Salvar deck');
    await page.click('#save-deck');
    await page.reload();
    await page.click('#build-deck');
    await page.selectOption('#saved-decks', { label: 'Aatrox na minha coleção · Regras pendentes' });
    assert.match(await page.locator('#deck-list').innerText(), /Aatrox/);
    assert.equal(await page.locator('#deck option').filter({ hasText: 'Aatrox na minha coleção' }).count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.locator('#collection-dialog').evaluate(element => element.scrollWidth <= element.clientWidth + 1));
    await page.screenshot({ path: path.resolve(__dirname, '../test-results/collection-v30-mobile.png') });
    assert.deepEqual(errors, []); assert.deepEqual(remote, []);
    console.log('PASS: normal collection, new ready decks, save/play Braum, all cards editable/saveable, pending rule decks preserved and mobile, offline.');
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
